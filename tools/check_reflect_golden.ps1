        Write-Output ("control: the first looks golden's order {0} problem(s); the moved copy {1}: {2}" -f $r4.Count, $r5.Count, ($r5 -join '; '))
        if ($fakeProblems -eq 0 -and $named -and $mutantProblems -eq $goldens.Count -and $r0.Count -eq 0 -and $r3.Count -ge 1 -and $lastFormat -ge 0 -and $r4.Count -eq 0 -and $r5.Count -ge 1) {
