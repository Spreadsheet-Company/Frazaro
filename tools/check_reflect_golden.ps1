# The relation forms a reader prints, and the phase each belongs to in the
# fixed order: the sheet rows, then the names, then the Tables, then the
# body, cell by cell.
$phases = @{ 'sheet' = 0; 'name' = 1; 'table' = 2; 'cell' = 3; 'formula' = 3; 'refers' = 3 }

# A text as its lines: line endings normalized, trailing blank lines dropped.
function Get-Lines([string]$text) {
    $t = $text -replace "`r`n", "`n"
    $lines = New-Object System.Collections.Generic.List[string]
    foreach ($l in ($t -split "`n")) { $lines.Add($l) }
    while ($lines.Count -gt 0 -and $lines[$lines.Count - 1] -eq '') { $lines.RemoveAt($lines.Count - 1) }
    return ,$lines
}

# The first quoted string of a form after its head, unescaped as WriteDatum
# escapes (`\"` and `\\`), or '' when there is none.
function Get-FirstString([string]$line) {
    $m = [regex]::Match($line, '^\([a-z]+ "((?:[^"\\]|\\.)*)"')
    if (-not $m.Success) { return '' }
    return ($m.Groups[1].Value -replace '\\(.)', '$1')
}

# The relation a line is a row of, or '' when the line is not a row.
function Get-Relation([string]$line) {
    $m = [regex]::Match($line, '^\(([a-z]+) ')
    if (-not $m.Success) { return '' }
    return $m.Groups[1].Value
}

# The fixed order, read off a golden's lines: a list of problems, empty when
# it holds.
function Test-Order($lines) {
    $problems = New-Object System.Collections.Generic.List[string]
    $sheets = New-Object System.Collections.Generic.List[string]
    $phase = 0
    $sheetAt = 0   # the index into $sheets the body has reached
    $n = 0
    foreach ($line in $lines) {
        $n++
        $rel = Get-Relation $line
        if ($rel -eq '' -or -not $phases.ContainsKey($rel)) { $problems.Add("line ${n}: not a relation row: $line"); continue }
        $p = $phases[$rel]
        if ($p -lt $phase) { $problems.Add("line ${n}: a $rel row after the $(@($phases.Keys | Where-Object { $phases[$_] -eq $phase })[0]) rows began: $line"); continue }
        $phase = $p
        if ($rel -eq 'sheet') { $sheets.Add((Get-FirstString $line)); continue }
        if ($p -ne 3) { continue }
        $sheet = Get-FirstString $line
        if ($rel -eq 'refers') { $sheet = ($sheet -split '!')[0] -replace "^'(.*)'$", '$1' -replace "''", "'" }
        $idx = $sheets.IndexOf($sheet)
        if ($idx -lt 0) { $problems.Add("line ${n}: a row of a sheet no sheet row named: $line"); continue }
        if ($idx -lt $sheetAt) { $problems.Add("line ${n}: a row of sheet $sheet after a later sheet's rows: $line"); continue }
        $sheetAt = $idx
    }
    return ,$problems
}

# The looks' rows inside a sheet's block (KERNEL.57), each its stage: the
# gridlines row begins the block, then the column rows, the row rows, the
# format rows, then the cells' rows.
$looksBody = @{ 'gridlines' = 0; 'column' = 1; 'row' = 2; 'format' = 3; 'cell' = 4; 'formula' = 4; 'value' = 4; 'style' = 4; 'refers' = 4 }

# Every quoted string of a row, unescaped as WriteDatum escapes.
function Get-Strings([string]$line) {
    $out = New-Object System.Collections.Generic.List[string]
    foreach ($m in [regex]::Matches($line, '"((?:[^"\\]|\\.)*)"')) { $out.Add(($m.Groups[1].Value -replace '\\(.)', '$1')) }
    return ,$out
}

# A column's letters as its number, A as 1.
function Get-ColumnNumber([string]$letters) {
    $n = 0
    foreach ($c in $letters.ToCharArray()) { $n = $n * 26 + ([int][char]$c - [int][char]'A' + 1) }
    return $n
}

# The looks' fixed order, read off a golden's lines: a list of problems,
# empty when it holds.
function Test-LooksOrder($lines) {
    $problems = New-Object System.Collections.Generic.List[string]
    $sheets = New-Object System.Collections.Generic.List[string]
    $head = 0
    $block = -1
    $stage = 0
    $lastColumn = 0; $lastRow = 0; $lastFormat = -1
    $cell = ''; $cellKind = ''; $cellStage = 0
    $n = 0
    foreach ($line in $lines) {
        $n++
        $rel = Get-Relation $line
        if ($rel -eq '') { $problems.Add("line ${n}: not a row: $line"); continue }
        if ($phases.ContainsKey($rel) -and $phases[$rel] -lt 3) {
            if ($head -eq 3) { $problems.Add("line ${n}: a $rel row after the sheets' blocks began: $line"); continue }
            if ($phases[$rel] -lt $head) { $problems.Add("line ${n}: a $rel row out of the header's order: $line"); continue }
            $head = $phases[$rel]
            if ($rel -eq 'sheet') { $sheets.Add((Get-FirstString $line)) }
            continue
        }
        if (-not $looksBody.ContainsKey($rel)) { $problems.Add("line ${n}: not a row of the looks: $line"); continue }
        $head = 3
        if ($rel -eq 'gridlines') {
            $idx = $sheets.IndexOf((Get-FirstString $line))
            if ($idx -le $block) { $problems.Add("line ${n}: a sheet's block out of tab order: $line"); continue }
            $block = $idx; $stage = 0; $lastColumn = 0; $lastRow = 0; $lastFormat = -1; $cell = ''
            continue
        }
        if ($block -lt 0) { $problems.Add("line ${n}: a row before any sheet's gridlines row: $line"); continue }
        $s = $looksBody[$rel]
        if ($s -lt $stage) { $problems.Add("line ${n}: a $rel row after its sheet's later rows began: $line"); continue }
        $stage = $s
        $strings = Get-Strings $line
        if ($rel -ne 'format' -and $rel -ne 'refers' -and $strings[0] -ne $sheets[$block]) {
            $problems.Add("line ${n}: a row of $($strings[0]) inside the block of $($sheets[$block]): $line"); continue
        }
        if ($rel -eq 'column') {
            $c = Get-ColumnNumber $strings[1]
            if ($c -le $lastColumn) { $problems.Add("line ${n}: a column row out of order: $line") }
            $lastColumn = $c
        } elseif ($rel -eq 'row') {
            $r = [int]([regex]::Match($line, '^\(row "(?:[^"\\]|\\.)*" (\d+) ').Groups[1].Value)
            if ($r -le $lastRow) { $problems.Add("line ${n}: a row row out of order: $line") }
            $lastRow = $r
        } elseif ($rel -eq 'format') {
            $f = [int]([regex]::Match($line, '^\(format (\d+) ').Groups[1].Value)
            if (($lastFormat -lt 0 -and $f -ne 0) -or ($lastFormat -ge 0 -and $f -le $lastFormat)) { $problems.Add("line ${n}: a format row out of order, format 0 first and ascending: $line") }
            $lastFormat = $f
        } elseif ($rel -eq 'cell' -or $rel -eq 'formula') {
            $cell = $strings[1]; $cellKind = $rel; $cellStage = 0
        } else {
            $addr = if ($rel -eq 'refers') { ($strings[0] -split '!')[-1] } else { $strings[1] }
            $want = @{ 'value' = 1; 'style' = 2; 'refers' = 3 }[$rel]
            if ($addr -ne $cell) { $problems.Add("line ${n}: a $rel row of $addr after the rows of $cell began: $line") }
            elseif ($rel -eq 'value' -and $cellKind -ne 'formula') { $problems.Add("line ${n}: a value row after a cell row, not a formula's: $line") }
            elseif ($want -lt $cellStage -or ($want -eq $cellStage -and $rel -ne 'refers')) { $problems.Add("line ${n}: a $rel row out of its cell's order: $line") }
            $cellStage = $want
        }
    }
    return ,$problems
}

# `<impl> <args>` with the door's stderr set aside: its exit code and every
# line of its stdout.
function Invoke-Door([string]$impl, [string[]]$doorArgs) {
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $global:LASTEXITCODE = 0
        $lines = & $impl @doorArgs 2>$null
        $code = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $old
    }
    if ($null -eq $code) { $code = 0 }
    $text = if ($null -eq $lines) { '' } else { (@($lines) | ForEach-Object { [string]$_ }) -join "`n" }
    return @{ ExitCode = [int]$code; Text = $text }
}

# One implementation against one golden: a list of problems, empty when its
# relations are the golden whole.
function Measure-Impl([string]$impl, $g) {
    $problems = New-Object System.Collections.Generic.List[string]
    $golden = Join-Path $repoRoot $g.Golden
    $fixture = Join-Path $repoRoot $g.Fixture
    if (-not (Test-Path $fixture)) { $problems.Add("$($g.Name): no fixture at $fixture"); return ,$problems }
    $doorArgs = @('reflect', $fixture)
    if ($g.Looks) { $doorArgs += '--looks' }
    $r = Invoke-Door $impl $doorArgs
    if ($r.ExitCode -eq 3) { $problems.Add("$($g.Name): reflect not attempted (exit 3), but the golden exists"); return ,$problems }
    if ($r.ExitCode -ne 0) { $problems.Add("$($g.Name): reflect exited $($r.ExitCode)"); return ,$problems }
    $want = Get-Lines ([System.IO.File]::ReadAllText($golden))
    $got = Get-Lines $r.Text
    $n = [Math]::Min($want.Count, $got.Count)
    for ($i = 0; $i -lt $n; $i++) {
        if ($want[$i] -ne $got[$i]) {
            $problems.Add("$($g.Name): differs at line $($i + 1) of $($want.Count): golden $($want[$i]) / door $($got[$i])")
            return ,$problems
        }
    }
    if ($want.Count -ne $got.Count) { $problems.Add("$($g.Name): the door printed $($got.Count) lines, the golden holds $($want.Count); they agree to line $n") }
    return ,$problems
}

# Every golden's floor and order: problems, and lines to print.
function Test-Goldens() {
    $problems = New-Object System.Collections.Generic.List[string]
    $lines = New-Object System.Collections.Generic.List[string]
    foreach ($g in $goldens) {
        $path = Join-Path $repoRoot $g.Golden
        if (-not (Test-Path $path)) { $problems.Add("$($g.Name): no golden at $path"); continue }
        $rows = Get-Lines ([System.IO.File]::ReadAllText($path))
        if ($rows.Count -lt $g.Floor) {
            $problems.Add("$($g.Name): the golden holds $($rows.Count) lines, below its floor of $($g.Floor)")
            $lines.Add("  $($g.Name): $($rows.Count) lines, BELOW THE FLOOR of $($g.Floor)  FAIL")
        } elseif ($rows.Count -gt $g.Floor) {
            $lines.Add("  $($g.Name): $($rows.Count) lines, above the floor of $($g.Floor) - raise the floor in this file")
        } else {
            $lines.Add("  $($g.Name): $($g.Floor) lines, at its floor")
        }
        $order = if ($g.Looks) { Test-LooksOrder $rows } else { Test-Order $rows }
        foreach ($p in $order) { $problems.Add("$($g.Name): $p"); $lines.Add("  $($g.Name): $p  FAIL") }
        if ($order.Count -eq 0 -and $g.Looks) { $lines.Add("  $($g.Name): the looks' order holds (the header, then each sheet's gridlines, columns, rows and formats before its cells, each cell's rows in their order)") }
        elseif ($order.Count -eq 0) { $lines.Add("  $($g.Name): the fixed order holds (sheets, names, tables, then the cells sheet by sheet)") }
    }
    return @{ Problems = $problems; Lines = $lines }
}

